// AssetRef는 자산 ID를 발견 항목(라벨 및 백엔드 CoverageNodeLabel)에 연결된 자산 참조로 변환합니다.
//값의 순서는 일관됩니다: URL > 도메인 이름 > IP > 애플리케이션 이름). "자산별" 보기의 트리는 이러한 참조에 의존합니다.
// 발견을 자산에 연결하십시오.
function assetRef(id: number): FindingAsset {
  const asset = assets.find((candidate) => candidate.id === id);
  if (!asset) throw new Error(`mock assetRef: unknown asset ${id}`);
  return {
    id: String(id),
    type: asset.type,
    label: asset.url || asset.domain || asset.ip || asset.app_name || String(id),
  };
}

